// Открыть n ближайших к from замков (ящики — только ключом). Возвращает открытые клетки.
function openNearest(s, n, from, ev) {
  const out = [];
  for (let k = 0; k < n; k++) {
    let best = -1;
    s.cells.forEach((c, i) => { if (canOpen(s, i) && c.k !== 'box' && (best < 0 || dist2(i, from) < dist2(best, from))) best = i; });
    if (best < 0) break;
    openCell(s, best, ev);
    out.push(best);
  }
  return out;
}
